# SQL Data Analysis – Music Store Database

/* Q1: Who is the senior most employee based on job title? */

SELECT *
FROM employee
ORDER BY levels DESC
LIMIT 1;


/* Q2: Which countries have the most invoices? */

SELECT
    billing_country,
    COUNT(*) AS total_invoices
FROM invoice
GROUP BY billing_country
ORDER BY total_invoices DESC;


/* Q3: What are the top 3 values of total invoice? */

SELECT total
FROM invoice
ORDER BY total DESC
LIMIT 3;


/* Q4: Which customers have made more than 5 separate invoice purchases? */

SELECT
    customer_id,
    COUNT(invoice_id) AS total_invoices
FROM invoice
GROUP BY customer_id
HAVING COUNT(invoice_id) > 5
ORDER BY total_invoices DESC;


/* Q5: Find the number of customers in each country. */

SELECT
    country,
    COUNT(customer_id) AS total_customers
FROM customer
GROUP BY country
ORDER BY total_customers DESC;


/* Q6: Find all invoices generated between January 1, 2017, and December 31, 2017. */

SELECT
    invoice_id,
    customer_id,
    invoice_date,
    total
FROM invoice
WHERE invoice_date >= '2017-01-01'
AND invoice_date < '2018-01-01'
ORDER BY invoice_date;


/* Q7: Find customers who have spent more than the average customer spending. */

SELECT
    customer_id,
    SUM(total) AS total_spending
FROM invoice
GROUP BY customer_id
HAVING SUM(total) > (
    SELECT AVG(customer_spending)
    FROM (
        SELECT SUM(total) AS customer_spending
        FROM invoice
        GROUP BY customer_id
    ) AS avg_spending
)
ORDER BY total_spending DESC;


/* Q8: Find the top 5 best-selling tracks based on quantity sold. */

SELECT
    track.name,
    SUM(invoice_line.quantity) AS total_sold
FROM invoice_line
JOIN track
    ON invoice_line.track_id = track.track_id
GROUP BY track.track_id, track.name
ORDER BY total_sold DESC
LIMIT 5;


/* Q9: Which city has the best customers?
We would like to throw a promotional Music Festival in the city where we made the most money.
Return the city name and the sum of all invoice totals. */

SELECT
    billing_city,
    SUM(total) AS total_revenue
FROM invoice
GROUP BY billing_city
ORDER BY total_revenue DESC
LIMIT 1;


/* Q10: Find the number of invoices generated in each month. */

SELECT
    EXTRACT(YEAR FROM invoice_date) AS year,
    EXTRACT(MONTH FROM invoice_date) AS month,
    COUNT(invoice_id) AS total_invoices
FROM invoice
GROUP BY
    EXTRACT(YEAR FROM invoice_date),
    EXTRACT(MONTH FROM invoice_date)
ORDER BY year, month;


/* Q11: Find the total revenue generated by each artist. */

SELECT
    artist.artist_id,
    artist.name,
    SUM(invoice_line.unit_price * invoice_line.quantity) AS revenue
FROM invoice_line
JOIN track
    ON invoice_line.track_id = track.track_id
JOIN album
    ON track.album_id = album.album_id
JOIN artist
    ON album.artist_id = artist.artist_id
GROUP BY artist.artist_id, artist.name
ORDER BY revenue DESC;


/* Q12: Who is the best customer?
The customer who has spent the most money will be declared the best customer.
Return the person who has spent the most money. */

SELECT
    customer.customer_id,
    customer.first_name,
    customer.last_name,
    SUM(invoice.total) AS total_spending
FROM customer
JOIN invoice
    ON customer.customer_id = invoice.customer_id
GROUP BY
    customer.customer_id,
    customer.first_name,
    customer.last_name
ORDER BY total_spending DESC
LIMIT 1;


/* Q13: Return email, first_name, last_name, and Genre of all Rock music listeners. */

SELECT DISTINCT
    customer.email,
    customer.first_name,
    customer.last_name,
    genre.name AS genre
FROM customer
JOIN invoice
    ON customer.customer_id = invoice.customer_id
JOIN invoice_line
    ON invoice.invoice_id = invoice_line.invoice_id
JOIN track
    ON invoice_line.track_id = track.track_id
JOIN genre
    ON track.genre_id = genre.genre_id
WHERE genre.name = 'Rock'
ORDER BY customer.email;


/* Q14: Let's invite the artists who have written the most Rock music in our dataset.
Return the artist name and total track count of the top 10 Rock artists. */

SELECT
    artist.artist_id,
    artist.name,
    COUNT(track.track_id) AS number_of_songs
FROM track
JOIN album
    ON album.album_id = track.album_id
JOIN artist
    ON artist.artist_id = album.artist_id
JOIN genre
    ON genre.genre_id = track.genre_id
WHERE genre.name = 'Rock'
GROUP BY artist.artist_id, artist.name
ORDER BY number_of_songs DESC
LIMIT 10;


/* Q15: Return all the track names that have a song length longer than the average song length.
Return the Name and Milliseconds for each track.
Order by song length with the longest songs listed first. */

SELECT
    name,
    milliseconds
FROM track
WHERE milliseconds > (
    SELECT AVG(milliseconds)
    FROM track
)
ORDER BY milliseconds DESC;

